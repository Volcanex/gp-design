// Regenerates src/ui/icons-data.ts from @phosphor-icons/core. The app imports
// exactly the glyphs listed here (inlined SVG, no icon font). Run after
// editing NAMES: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const NAMES = [
  'selection', 'arrows-out-cardinal', 'magnifying-glass', 'hand', 'paint-brush', 'pencil-simple', 'eraser',
  'paint-bucket', 'gradient', 'eyedropper', 'swap', 'stamp', 'text-t', 'line-segment', 'shapes',
  'eye', 'eye-slash', 'folder', 'folder-open', 'circle-half', 'caret-down', 'caret-right', 'copy', 'diamond',
  'dots-six-vertical', 'plus', 'trash', 'x', 'play', 'pause', 'arrow-line-down', 'image', 'arrows-left-right',
  'sun', 'moon', 'monitor', 'check', 'mask-happy', 'sliders-horizontal', 'cube', 'polygon', 'sparkle',
  'film-strip', 'square', 'circle', 'star', 'waveform', 'arrow-counter-clockwise', 'arrow-clockwise',
];

const require = createRequire(import.meta.url);
const pkg = join(dirname(require.resolve('@phosphor-icons/core/assets/regular/eye.svg')), '../..');
const out = [
  '/* Generated by scripts/gen-icons.mjs from @phosphor-icons/core (regular). Do not edit; edit the NAMES list in the script. */',
  '',
  'export const ICON_SVG = {',
];
for (const name of NAMES) {
  const svg = readFileSync(join(pkg, 'assets/regular', `${name}.svg`), 'utf8')
    .replace('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor">', '<svg class="gd-icon" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" focusable="false">')
    .trim();
  out.push(`  '${name}': ${JSON.stringify(svg)},`);
}
out.push('} as const;', '');
writeFileSync(new URL('../src/ui/icons-data.ts', import.meta.url), out.join('\n'));
console.log(`wrote ${NAMES.length} icons`);
